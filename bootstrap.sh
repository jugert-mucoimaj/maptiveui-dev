#!/usr/bin/env bash
#
# bootstrap.sh — one-time setup for the @maptiveui/tunable repo.
#
# What it does:
#   1. Installs dependencies
#   2. Runs typecheck + build to verify everything works
#   3. Initializes git (if not already)
#   4. Adds the remote (or updates it)
#   5. Makes the first commit and pushes to GitHub
#
# Run this once after cloning or extracting the package folder.
# For subsequent releases, use ./release.sh instead.
#

set -euo pipefail

REPO_URL="https://github.com/jugert-mucoimaj/maptiveui-dev.git"
BRANCH="main"
COMMIT_MSG="Initial commit: @maptiveui/tunable v0.1.0"

cyan()  { printf "\033[36m%s\033[0m\n" "$*"; }
green() { printf "\033[32m%s\033[0m\n" "$*"; }
red()   { printf "\033[31m%s\033[0m\n" "$*" >&2; }

require() {
  command -v "$1" >/dev/null 2>&1 || {
    red "✗ Missing required command: $1"
    exit 1
  }
}

require git
require node
require npm

cyan "▸ Installing dependencies..."
npm install

cyan "▸ Running typecheck..."
npm run typecheck

cyan "▸ Building to verify..."
npm run build

if [ ! -d ".git" ]; then
  cyan "▸ Initializing git repo..."
  git init
  git branch -M "$BRANCH"
else
  cyan "▸ Git already initialized, skipping init."
fi

if git remote get-url origin >/dev/null 2>&1; then
  existing=$(git remote get-url origin)
  if [ "$existing" != "$REPO_URL" ]; then
    cyan "▸ Updating remote origin from $existing to $REPO_URL"
    git remote set-url origin "$REPO_URL"
  else
    cyan "▸ Remote origin already points to $REPO_URL"
  fi
else
  cyan "▸ Adding remote origin: $REPO_URL"
  git remote add origin "$REPO_URL"
fi

# If this is our first run AND remote already has content (e.g. a LICENSE
# generated by GitHub when the repo was created), pull it down first.
# Otherwise our push gets rejected as non-fast-forward.
#
# Strategy: snapshot our local files (EXCEPT LICENSE — we want GitHub's),
# hard-reset to origin/main, then restore our snapshot on top. GitHub's
# LICENSE stays, everything else of ours wins.
HAS_LOCAL_COMMITS=$(git rev-list --count HEAD 2>/dev/null || echo "0")
REMOTE_HAS_BRANCH=0
if git ls-remote --heads origin "$BRANCH" 2>/dev/null | grep -q "$BRANCH"; then
  REMOTE_HAS_BRANCH=1
fi

if [ "$HAS_LOCAL_COMMITS" = "0" ] && [ "$REMOTE_HAS_BRANCH" = "1" ]; then
  cyan "▸ Remote has existing content — pulling first so we can fast-forward..."

  TMPDIR=$(mktemp -d)
  trap "rm -rf '$TMPDIR'" EXIT

  # Snapshot local files, excluding:
  #   .git        — git state, obviously
  #   LICENSE     — we want GitHub's version
  #   node_modules, dist — generated, should never be committed
  tar cf - \
    --exclude='./.git' \
    --exclude='./LICENSE' \
    --exclude='./node_modules' \
    --exclude='./dist' \
    . | (cd "$TMPDIR" && tar xf -)

  # Sync local history with remote; this overwrites working tree with remote's content
  git fetch origin "$BRANCH"
  git reset --hard "origin/$BRANCH"

  # Restore our files on top (our README / package.json / etc. win over any remote ones)
  (cd "$TMPDIR" && tar cf - .) | tar xf -

  rm -rf "$TMPDIR"
  trap - EXIT

  cyan "✓ Pulled remote LICENSE; your local files preserved."
fi

cyan "▸ Staging files..."
git add -A

if git diff --cached --quiet; then
  cyan "▸ Nothing to commit."
else
  git commit -m "$COMMIT_MSG"
fi

cyan "▸ Pushing to $REPO_URL..."
git push -u origin "$BRANCH"

green "✓ Repository is live at $REPO_URL"
echo ""
echo "Next steps:"
echo "  • Verify the push at https://github.com/jugert-mucoimaj/maptiveui-dev"
echo "  • When ready to publish: ./release.sh patch   (or minor / major)"
